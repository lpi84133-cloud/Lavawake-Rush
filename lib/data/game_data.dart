  static final List<LevelDef> levels = _buildLevels();

  static List<LevelDef> _buildLevels() {
    final out = <LevelDef>[];
    var global = 0;
    for (final region in regions) {
      for (var i = 0; i < region.levelCount; i++) {
        final isBoss = i == region.levelCount - 1;
        final difficulty = 1 + region.index * 0.55 + i * 0.14;
        out.add(
          LevelDef(
            regionIndex: region.index,
            indexInRegion: i,
            globalIndex: global,
            name: isBoss ? 'Warden of ${region.name.split(' ').first}' : _levelNames[i % _levelNames.length],
            distance: 900 + region.index * 240 + i * 130,
            difficulty: difficulty,
            isBoss: isBoss,
            bossId: isBoss ? _bossOrder[region.index] : null,
            rewards: {
              ResourceKind.magma: 80 + region.index * 32 + i * 11,
              if (i.isEven) ResourceKind.obsidian: 8 + region.index * 4,
              if (i % 3 == 1) ResourceKind.alloy: 7 + region.index * 4,
              if (i % 3 == 2) ResourceKind.shards: 7 + region.index * 4,
              if (isBoss) ResourceKind.cores: 3 + region.index,
            },
          ),
        );
        global++;
      }
    }
    return out;
  }

  static LevelDef levelAt(int index) => levels[index.clamp(0, levels.length - 1)];

